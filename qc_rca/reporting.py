"""Render a stored investigation report as a downloadable Markdown incident report."""


def _pct(v):
    return "n/a" if v is None else f"{v:.1%}"


def report_to_markdown(report: dict, created_at: str | None = None, user: str | None = None) -> str:
    r = report
    scope = r.get("scope") or {}
    out = [
        f"# Incident investigation report — {r['investigation_id']}",
        "",
        f"- **Question:** {r['question']}",
        f"- **Intent:** {r['intent']} (classified by {r.get('intent_source', 'rules')})",
        f"- **Status:** {r['status']}",
        f"- **Generated:** {created_at or 'n/a'}" + (f" by {user}" if user else ""),
        f"- **Scope:** stores={scope.get('stores') or '-'}, cities={scope.get('cities') or '-'}, "
        f"date={scope.get('date') or '-'}, hours={scope.get('hour_label') or 'all'}",
        f"- **Confidence:** {r['confidence']['level']}",
        "",
    ]
    if r.get("narrative"):
        out += ["## Summary", "", r["narrative"],
                f"", f"_Generated by local model {r['llm'].get('model')}; numbers verified against evidence._", ""]
    out += ["## Findings", "", r["answer_markdown"], ""]
    if r.get("observed_metrics"):
        out += ["## Observed metrics", "", "| Metric | Value | Unit | Evidence |", "|---|---|---|---|"]
        for m in r["observed_metrics"]:
            v = m["value"]
            v = _pct(v) if m.get("unit") == "ratio" and isinstance(v, (int, float)) else v
            out.append(f"| {m['name']} | {v} | {m.get('unit') or ''} | {m['evidence_id']} |")
        out.append("")
    if r.get("contributing_factors"):
        out += ["## Probable contributing factors", ""]
        for f in r["contributing_factors"]:
            out.append(f"- **{f['factor']}** (hours {f['hours']}): {f['assessment']} "
                       f"Evidence: {', '.join(f['evidence_ids'][:6])}")
        out.append("")
    if r.get("corrective_actions"):
        out += ["## Suggested corrective actions", ""]
        for a in r["corrective_actions"]:
            cites = f" [{', '.join(a['citation_ids'])}]" if a["citation_ids"] else ""
            out.append(f"- {a['action']}{cites} — _{a['source_note']}_")
        out.append("")
    if r.get("next_steps"):
        out += ["## Recommended next investigative steps", "", *[f"- {s}" for s in r["next_steps"]], ""]
    if r.get("missing_data"):
        out += ["## Missing data", "", *[f"- {m}" for m in r["missing_data"]], ""]
    if r["confidence"].get("limitations"):
        out += ["## Confidence limitations", "", *[f"- {x}" for x in r["confidence"]["limitations"]], ""]
    if r.get("evidence"):
        out += ["## Evidence", ""]
        for e in r["evidence"]:
            out.append(f"- **{e['id']}** ({e['kind']}, {e['source']}): {e['summary']}")
        out.append("")
    if r.get("citations"):
        out += ["## Sources", ""]
        for c in r["citations"]:
            sample = " — SAMPLE DOCUMENT (illustrative, not company policy)" if c["is_sample"] else ""
            out.append(f"- [{c['id']}] `{c['source_path']}` — {c.get('heading') or c['title']}{sample}")
        out.append("")
    if r.get("validation"):
        out += ["## Validation checks", ""]
        for v in r["validation"]:
            out.append(f"- {'PASS' if v['passed'] else 'FAIL'} {v['name']}: {v['detail']}")
        out.append("")
    out += ["---", f"_{r.get('disclaimer', '')}_", ""]
    return "\n".join(out)
